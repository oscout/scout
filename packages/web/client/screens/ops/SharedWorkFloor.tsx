  const [modelStudio, setModelStudio] = useState(false);
  const [renderedPrototype, setRenderedPrototype] = useState(true);
  // Reserve each character once; roster updates never duplicate or reassign a friend.
  const characterOwners = useRef<string[]>([]);
  for (const lane of lanes) {
    if (characterOwners.current.length >= workerCharacters.length) break;
    if (!characterOwners.current.includes(lane.id)) characterOwners.current.push(lane.id);
  }
  const [furniture, setFurniture] = useState(false);
  const [boundaries, setBoundaries] = useState(false);
  const [teamsOpen, setTeamsOpen] = useState(false);
  const [layersOpen, setLayersOpen] = useState(false);
  const [paused, setPaused] = useState(false);
  const viewport = useRef<HTMLDivElement>(null);
  const [size, setSize] = useState({ width: 900, height: 500 });
  const [workspaceKey, setWorkspaceKey] = useState<string | null>(null);
  const [projection, setProjection] = useState<MapProjection>("flat");
  const [zoom, setZoom] = useState(1);
  const [pan, setPan] = useState({ x: 0, y: 0 });
  const [actorOffsets, setActorOffsets] = useState<Record<string, { x: number; y: number }>>({});
  const [draggingActor, setDraggingActor] = useState<string | null>(null);
  const actorDrag = useRef<{ id: string; sx: number; sy: number; x: number; y: number; baseX: number; baseY: number; moved: boolean } | null>(null);
  const suppressActorClick = useRef(false);
  const drag = useRef<{ x: number; y: number; px: number; py: number } | null>(null);
  useEffect(() => {
    if (!viewport.current) return;
    const observer = new ResizeObserver(([entry]) => setSize({ width: entry.contentRect.width, height: entry.contentRect.height }));
    observer.observe(viewport.current); return () => observer.disconnect();
  }, [workRun]);

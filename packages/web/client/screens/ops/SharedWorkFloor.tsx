  const actorName = (lane: AgentLane) => floorCharacterName(lane).label;
  for (const edge of familyEdges) {
    if (edge.child.id === selectedId) connections.set(edge.parent.id, { lane: edge.parent, reason: "Parent session" });
    if (edge.parent.id === selectedId) connections.set(edge.child.id, { lane: edge.child, reason: "Child session" });
  }
  const connected = new Set(connections.keys());
  if (exchangePair) exchangePair.forEach(id=>connected.add(id));
  const exchanges = floorExchanges(lanes, now, brokerMessages);
  const exchangePairs = new Map<string,[string,string]>();
  for (const e of exchanges) exchangePairs.set([e.from,e.to].sort().join(":"), [e.from,e.to]);
  for (const { parent, child } of familyEdges) {
    const key = [parent.id, child.id].sort().join(":");
    if (!exchangePairs.has(key)) exchangePairs.set(key, [parent.id, child.id]);
  }
  const pairStillExists = !!exchangePair && [...exchangePairs.values()].some(pair => pair.every(id => exchangePair.includes(id)));
  useEffect(() => { if (exchangePair && !pairStillExists) setExchangePair(null); }, [pairStillExists, exchangePair]);
